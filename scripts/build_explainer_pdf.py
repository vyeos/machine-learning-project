"""ReportLab script that renders PROJECT_EXPLAINER.pdf - a plain-language
handout explaining the whole ML project (content mirrors results files).
Run:  python scripts/build_explainer_pdf.py
"""
from pathlib import Path
from datetime import datetime

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.lib import colors
from reportlab.platypus import (HRFlowable, PageBreak, Paragraph,
                                SimpleDocTemplate, Spacer, Table, TableStyle, KeepTogether)

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "PROJECT_EXPLAINER.pdf"

sheets = getSampleStyleSheet()
BODY_FONT = "Helvetica"


def st(name, parent, **kw):
    return ParagraphStyle(name, parent=parent, **kw)


STYLES = {
    "title": st("t", sheets["Title"], fontSize=22, fontName=BODY_FONT, spaceAfter=6),
    "subtitle": st("st", sheets["Normal"], fontSize=11, textColor=colors.HexColor("#777777"),
                   alignment=1, fontName=BODY_FONT, spaceAfter=14),
    "h1": st("h1", sheets["Heading1"], fontSize=14, fontName=BODY_FONT,
             spaceBefore=14, spaceAfter=6, textColor=colors.HexColor("#1a2a5a")),
    "body": st("b", sheets["BodyText"], fontName=BODY_FONT, fontSize=10.5, leading=15),
    "li": st("li", sheets["BodyText"], fontName=BODY_FONT, fontSize=10.5, leftIndent=14, spaceAfter=4),
    "cap": st("c", sheets["BodyText"], fontName=BODY_FONT, fontSize=8.5,
              textColor=colors.HexColor("#8a8a8a"), alignment=1, spaceBefore=4, spaceAfter=10),
}


def T(rows, widths=None, header=True):
    t = Table(rows, colWidths=widths, repeatRows=1 if header else 0)
    style = [("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#b7b7b7")),
             ("FONTSIZE", (0, 0), (-1, -1), 8.8),
             ("FONTNAME", (0, 0), (-1, -1), BODY_FONT),
             ("VALIGN", (0, 0), (-1, -1), "MIDDLE")]
    if header:
        t.setStyle(StyleSheetHeader())
    t.setStyle(style)
    return t


def StyleSheetHeader():
    from reportlab.platypus import Paragraph  # noqa (keep import local for clarity)
    import reportlab.lib.styles as ls
    from reportlab.lib import colors as C
    style = TableStyle([("BACKGROUND", (0, 0), (-1, 0), C.HexColor("#dcd9f0")),
                        ("FONTNAME", (0, 0), (-1, 0), BODY_FONT)])
    return style


def page(html):
    return Paragraph(html, STYLES["body"])


def li(txt):
    return Paragraph("• " + txt, STYLES["li"])


def main():
    doc = SimpleDocTemplate(str(OUT), pagesize=A4,
                            leftMargin=2.2 * cm, rightMargin=2.2 * cm,
                            topMargin=2.0 * cm, bottomMargin=2.0 * cm)

    def decorate(canvas, _d):
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.HexColor("#999999"))
        canvas.drawCentredString(A4[0] / 2, 1.2 * cm, f"Page {_d.page}")
        canvas.restoreState()

    E = []  # elements
    A = E.append

    A(Paragraph("Cybersecurity Intrusion Detection Using Machine Learning", STYLES["title"]))
    A(Paragraph("Project explainer for team members &middot; Course ECSCI24302 &middot; "
                "generated " + datetime.now().strftime("%Y-%m-%d"), STYLES["subtitle"]))

    # ---- 1. What this project is ----
    A(Paragraph("1. What this project is", STYLES["h1"]))
    A(page("A supervised classifier that reads records of network traffic (network \"flows\") "
           "and predicts whether each one is <b>benign</b> or <b>malicious</b>. The dataset is "
           "<b>UNSW-NB15</b> (UNSW Canberra Cyber, 2015): real captured traffic plus synthetic "
           "modern attacks. The whole pipeline is deterministic (random_state=42) so every number "
           "is reproducible and identical across all files."))

    # ---- 2. Deliverables ----
    A(Paragraph("2. What has been produced (deliverables)", STYLES["h1"]))
    for t in [
        "A fully <b>executed Jupyter notebook</b> covering the complete pipeline end-to-end.",
        "A <b>project proposal</b> (DOCX) and a <b>final report</b> (DOCX + PDF) with chapters, figure captions and references.",
        "A <b>presentation deck</b> (PPTX) embedding the real figures generated by the pipeline.",
        "<b>Two browser frontends</b> for a live demo (Streamlit dashboard and a single-page HTML app).",
        "A <b>fitted model</b> (joblib) with a metadata file, so deploying needs no retraining.",
        "Unit tests (pytest) that exercise the pipeline.",
    ]:
        E.append(li(t))

    # ---- 3. The pipeline ----
    A(Paragraph("3. The pipeline, step by step", STYLES["h1"]))
    A(T([
        ["Stage", "What happens", "Output"],
        ["Load + validate", "Rows, columns, id ranges, missing cells, label consistency are all re-verified at runtime.", "dataset_facts.json"],
        ["Quality audit", "Counts duplicate flow rows and drops constants using training data only (test is never cleaned).", "quality_audit.json"],
        ["EDA", "Class balance, feature histograms, box plots, correlation matrix (figures 1-7).", "eda_summary.json"],
        ["Split", "Official training partition is the modeling source; the test partition stays untouched until the last step.", "-"],
        ["Feature engineering", "16 derived features (totals, bytes/packet, send/receive ratios, loss rates, log1p twins, ftp/http flags).", "in-pipeline"],
        ["Preprocessing", "Median imputer; StandardScaler only for the linear model; one-hot for proto/service/state.", "in-pipeline"],
        ["Baseline", "DummyClassifier (most_frequent) sets the floor; never eligible for selection.", "-"],
        ["ML models", "LogisticRegression, DecisionTree, RandomForest, HistGradientBoosting (identical pipelines).", "-"],
        ["Tuning", "GridSearchCV / RandomizedSearchCV, cv=3, scoring=F1; full search spaces stored.", "tuning_*.json"],
        ["Final test", "One pass on the untouched test partition with the threshold fixed beforehand (0.480).", "metrics + figures"],
    ], widths=[3.3 * cm, 10.0 * cm, 3.7 * cm]))

    # ---- 4. Results table ----
    results_block = [
        Paragraph("4. Final results (single pass on the untouched test partition)", STYLES["h1"]),
        T([
            ["Model", "Accuracy", "Precision", "Recall", "F1", "ROC-AUC", "AP"],
            ["HistGradientBoosting (tuned)", "0.8712", "0.8154", "0.9903", "0.8944", "0.9868", "0.9903"],
            ["RandomForest (tuned)", "0.8663", "0.8099", "0.9894", "0.8907", "0.9841", "0.9881"],
            ["DecisionTree (tuned)", "0.8601", "0.8098", "0.9894", "0.8847", "0.9693", "0.9680"],
            ["LogisticRegression (tuned)", "0.8100", "0.7550", "0.9696", "0.8490", "0.9531", "0.9650"],
            ["Dummy (baseline floor)", "0.5506", "0.5506", "1.0000", "0.7102", "0.5000", "0.5506"],
        ]),
        Spacer(1, 8),
        page("Chosen model's confusion matrix (n=82,332): tn=26,836, fp=10,164, fn=440, tp=44,892. "
             "Key numbers to memorise: recall ~99%, FPR ~27.5%, F1 0.8944."),
    ]
    E.append(KeepTogether(results_block[:-1]))

    # ---- 5. Limitations / honesty ----
    A(Paragraph("5. Honest findings and limitations (say these in the viva)", STYLES["h1"]))
    for t in [
        "<b>The FPR is high (27.47%)</b> mainly because of a distribution shift between the official train and test partitions (68% vs 55% attack share). We do not patch it after the fact - we document it.",
        "<b>sttl dominates importance (0.375)</b> partly because it is a schema artifact of the synthetic capture; treat feature importance as indicative, never causal.",
        "<b>The release carries overlapping rows</b>: 4,247 duplicate flows between the two files (5.16%); F1 drops from 0.8944 to 0.8902 when only unique rows are scored.",
        "<b>Multi-class is harder than binary</b>: macro-F1 0.5129 across 9 families; Analysis (38.26%) and DoS (12.40%) recall are the weak spots.",
        "<b>Baseline never loses</b>: the dummy model shows the task is discriminative rather than trivial.",
        "<b>Operating point</b>: max F1 favours recall, matching the deployment brief (\"catch attacks\"); real environments re-calibrate per false-alarm cost.",
    ]:
        E.append(li(t))

    # ---- 6. Code map ----
    A(Paragraph("6. Where everything lives in the code", STYLES["h1"]))
    for t in [
        "<b>src/data_loading.py</b> - loading, validation, DATASET_INFO, eda helpers.",
        "<b>src/preprocessing.py</b> - audit + FeatureEngineer + preprocessor factory.",
        "<b>src/evaluate.py</b> - metrics suite and all evaluation figures.",
        "<b>src/train.py</b> - the pipeline orchestrator and runbook.",
        "<b>src/predict.py</b> - the IntrusionPredictor used for fixed threshold inference.",
        "<b>app/app.py</b> (Streamlit) and <b>app/api.py</b> + <b>frontend/index.html</b> (HTML demo).",
        "<b>tests/test_pipeline.py</b> - pytest suite (5 tests, all pass).",
    ]:
        E.append(li(t))

    # ---- 7. Reproduce ----
    A(Paragraph("7. Reproduce it yourself", STYLES["h1"]))
    A(page("<b>pip install -r requirements.txt</b> <br/>"
           "then run <b>python -m src.download_data</b> (fetch + verify) and "
           "<b>python -m src.train</b> (about 6 minutes). All artefacts, figures and "
           "the results table regenerate deterministically (random_state=42). "
           "The model is benchmark-grade, not yet production-grade: re-calibrate the "
           "threshold against your own environment before using it anywhere real."))

    doc.build(E, onFirstPage=decorate, onLaterPages=decorate)
    print("Saved:", OUT)


if __name__ == "__main__":
    main()
